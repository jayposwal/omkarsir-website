def main():
    slot = os.environ.get("TODAY_QUIZ_SLOT", "").strip()
    if slot not in QUIZZES:
        raise SystemExit(f"Unknown TODAY_QUIZ_SLOT: {slot}")

    token = os.environ.get("TELEGRAM_BOT_TOKEN", "").strip()
    chat_id = os.environ.get("TELEGRAM_CHAT_ID", "@omkarsirofficial").strip()
    dry_run = os.environ.get("DRY_RUN") == "1"
    if not token and not dry_run:
        raise SystemExit("TELEGRAM_BOT_TOKEN is required")

    for question, options, correct, explanation in QUIZZES[slot]:
        payload = {
            "chat_id": chat_id,
            "question": question,
            "options": options,
            "type": "quiz",
            "correct_option_id": correct,
            "explanation": explanation,
            "is_anonymous": True,
        }
        if dry_run:
            print(json.dumps(payload, ensure_ascii=False))
            continue
        request = urllib.request.Request(
            f"https://api.telegram.org/bot{token}/sendPoll",
            data=json.dumps(payload, ensure_ascii=False).encode("utf-8"),
            headers={"Content-Type": "application/json"},
        )
        try:
            response = json.loads(urllib.request.urlopen(request, timeout=30).read())
        except urllib.error.HTTPError as exc:
            raise SystemExit(exc.read().decode("utf-8", "replace")) from exc
        if not response.get("ok"):
            raise SystemExit(response.get("description", "Telegram rejected the poll"))
        print(f"Posted {slot}: message {response['result']['message_id']}")


if __name__ == "__main__":
    main()
