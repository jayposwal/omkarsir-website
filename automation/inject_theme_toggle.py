THEME_BODY = "<button id=\"themeTgl\" class=\"theme-tgl\" onclick=\"toggleNiedTheme()\" aria-label=\"थीम बदलें (Light/Dark)\" title=\"थीम बदलें\">🌙</button><script>(function(){var K='niedQuizTheme';window.toggleNiedTheme=function(){var light=document.body.classList.toggle('light-theme');localStorage.setItem(K, light?'light':'dark');var b=document.getElementById('themeTgl');if(b)b.textContent=light?'☀️':'🌙';};var saved=localStorage.getItem(K);if(saved==='light'){document.body.classList.add('light-theme');}var b=document.getElementById('themeTgl');if(b)b.textContent=(saved==='light')?'☀️':'🌙';})();</script>"

# Only touch dark-themed interactive quiz pages generated by the NIEd quiz
# template (identified by this exact body background), never the light-themed
# Daily Current Affairs pages or any unrelated page on the site.
DARK_MARKER = "background:#0a0f1e"

TARGET_GLOBS = ["quizzes/*.html", "ES*.html"]


def find_candidates():
    seen = set()
    for pattern in TARGET_GLOBS:
        for path in glob.glob(pattern):
            if path in seen:
                continue
            seen.add(path)
            yield path


def main():
    changed_files = []
    for path in find_candidates():
        try:
            with open(path, encoding="utf-8") as f:
                content = f.read()
        except Exception:
            continue

        if DARK_MARKER not in content:
            continue  # not one of our dark quiz pages
        if "theme-tgl" in content:
            continue  # already has the toggle
        if "</style>" not in content or "<body>" not in content:
            continue  # not the expected template shape, skip safely

        new_content = content.replace("</style>", THEME_CSS + "\n</style>", 1)
        new_content = new_content.replace("<body>", "<body>" + THEME_BODY, 1)

        with open(path, "w", encoding="utf-8") as f:
            f.write(new_content)
        changed_files.append(path)

    if changed_files:
        print(f"Injected theme toggle into {len(changed_files)} file(s):")
        for f in changed_files:
            print(" -", f)
    else:
        print("No new quiz pages needed the theme toggle.")

    gh_out = os.environ.get("GITHUB_OUTPUT")
    if gh_out:
        with open(gh_out, "a", encoding="utf-8") as f:
            f.write(f"changed={'true' if changed_files else 'false'}\n")


if __name__ == "__main__":
    main()
