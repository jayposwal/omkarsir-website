#!/usr/bin/env python3
"""
Auto-injects the NIEd Quiz Light/Dark theme toggle into any dark-themed
quiz HTML file under quizzes/ that doesn't have it yet.

Safe to run repeatedly (idempotent) — files that already contain the
'theme-tgl' marker are skipped untouched.

Usage: python3 automation/inject_theme_toggle.py
Exits with code 0 always; prints which files were changed.
Sets GITHUB_OUTPUT `changed=true/false` when run inside GitHub Actions.
"""
import glob
import os
import re

