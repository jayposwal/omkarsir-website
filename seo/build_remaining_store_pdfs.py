def update_store_html():
    store_path = os.path.join(ROOT, "store.html")
    with open(store_path, "r", encoding="utf-8") as f:
        store = f.read()

    for item in REMAINING_PDFS:
        slug = item["slug"]
        pattern = re.compile(
            r'<article class="card[^"]*"[^>]*>(?:(?!</article>).)*?href="/' + re.escape(slug) + r'"(?:(?!</article>).)*?</article>',
            re.S,
        )
        new_card = render_store_card(item)
        store, count = pattern.subn(lambda _m: new_card, store, count=1)
        assert count == 1, f"Could not find unique card for {slug} in store.html (found {count})"

    store = store.replace(
        "<span>💎 भारत GK के 10 विषय अब ₹49 में उपलब्ध</span>",
        "<span>💎 सभी 30 विषयों की PDF अब ₹49 में उपलब्ध</span>",
    )
    store = store.replace(
        "विषय और परीक्षा के अनुसार PDF खोजें। हर पेज पर उपलब्ध जानकारी और सैंपल देखें; भुगतान लिंक तैयार होने पर ही खरीदें।",
        "विषय और परीक्षा के अनुसार PDF चुनें — सिर्फ़ ₹49 में Razorpay से भुगतान कर तुरंत PDF डाउनलोड करें।",
    )

    with open(store_path, "w", encoding="utf-8") as f:
        f.write(store)


def main():
    for item in REMAINING_PDFS:
        out_path = os.path.join(ROOT, item["slug"])
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(render_page(item))
        if not item.get("skip_download_gen"):
            dl_slug = item.get("download_slug") or f"download-{item['slug']}"
            dl_path = os.path.join(ROOT, dl_slug)
            with open(dl_path, "w", encoding="utf-8") as f:
                f.write(render_download_page(item))
        print("Built:", item["slug"])
    update_store_html()
    print("Updated: store.html with all", len(REMAINING_PDFS), "remaining cards")


if __name__ == "__main__":
    main()
